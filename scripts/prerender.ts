import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { RAW_RECIPES } from '../src/data/recipesData.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const distDir = path.resolve(__dirname, '../dist');
const siteUrl = 'https://purnomoweb.github.io/dapurfyp';

function generatePrerender() {
  if (!fs.existsSync(distDir)) {
    console.error('Error: dist directory does not exist. Run vite build first.');
    process.exit(1);
  }

  const indexPath = path.join(distDir, 'index.html');
  if (!fs.existsSync(indexPath)) {
    console.error('Error: dist/index.html does not exist.');
    process.exit(1);
  }

  const baseHtml = fs.readFileSync(indexPath, 'utf-8');

  // Find hashed images generated by Vite in dist/assets
  const assetsDir = path.join(distDir, 'assets');
  const assetFiles = fs.existsSync(assetsDir) ? fs.readdirSync(assetsDir) : [];
  const findAssetFile = (keyword: string): string => {
    const match = assetFiles.find((f) => f.toLowerCase().includes(keyword.toLowerCase()) && f.endsWith('.jpg'));
    return match ? `assets/${match}` : '';
  };

  const keyToAssetKeyword: Record<string, string> = {
    'mie-jebew': 'mie_jebew',
    'seblak': 'seblak_coet',
    'matcha': 'matcha_cloud',
    'cireng': 'cireng_salju',
    'cromboloni': 'cromboloni',
  };

  // 1. Generate Static HTML Pages for Each Recipe (SSG)
  for (const recipe of RAW_RECIPES) {
    const recipeDir = path.join(distDir, 'resep', recipe.slug);
    fs.mkdirSync(recipeDir, { recursive: true });

    const recipeCanonical = `${siteUrl}/resep/${recipe.slug}/`;
    const fullTitle = `${recipe.title} – Resep Viral DapurFYP`;
    const fullSummary = recipe.summary.replace(/"/g, '&quot;');
    const assetRelPath = findAssetFile(keyToAssetKeyword[recipe.imageKey] || 'mie_jebew');
    const ogImageUrl = assetRelPath ? `${siteUrl}/${assetRelPath}` : `${siteUrl}/og-image.jpg`;

    // Schema.org Recipe Structured Data JSON-LD
    const flatIngredients = recipe.ingredientGroups.flatMap((group) => group.items);
    const recipeJsonLd = {
      '@context': 'https://schema.org',
      '@type': 'Recipe',
      'name': recipe.title,
      'description': recipe.summary,
      'image': [ogImageUrl],
      'recipeCategory': recipe.categoryLabel,
      'recipeIngredient': flatIngredients,
      'recipeInstructions': recipe.instructions.map((step) => ({
        '@type': 'HowToStep',
        'position': step.stepNumber,
        'name': step.title,
        'text': step.description,
      })),
      'author': {
        '@type': 'Organization',
        'name': 'DapurFYP',
        'url': siteUrl,
      },
    };

    // Pre-rendered HTML markup for crawlers (Googlebot, Bing, etc.)
    const preRenderedContent = `
      <article class="max-w-3xl mx-auto px-4 sm:px-6 py-8 relative">
        <header class="mb-8">
          <div class="text-xs font-semibold text-[#f59e0b] mb-2 uppercase tracking-wide">
            ${recipe.categoryLabel}
          </div>
          <h1 class="text-2xl sm:text-3xl md:text-4xl font-bold tracking-tight text-[#ededef] leading-tight mb-3">
            ${recipe.title}
          </h1>
          <p class="text-sm text-[#9ca3af] leading-relaxed mb-6">
            ${recipe.summary}
          </p>
          <div class="border border-[#262830] rounded-none overflow-hidden bg-[#181a1f]">
            <img src="../../${assetRelPath}" alt="${recipe.title}" class="w-full h-64 sm:h-84 object-cover rounded-none" />
          </div>
        </header>

        <nav aria-label="Daftar Isi" class="mb-10 p-4 border border-[#262830] rounded-none bg-[#16171b]">
          <div class="text-xs font-bold uppercase tracking-wider text-[#ededef] mb-2">Daftar Isi</div>
          <ol class="space-y-1 text-xs text-[#9ca3af]">
            ${recipe.tableOfContents.map((toc, i) => `<li><a href="#${toc.id}" class="hover:text-[#f59e0b]">${i + 1}. ${toc.label}</a></li>`).join('')}
          </ol>
        </nav>

        <section id="bahan" class="mb-10 scroll-mt-24">
          <h2 class="text-xl font-bold text-[#ededef] tracking-tight pb-2 mb-5 border-b border-[#262830]">Bahan-Bahan</h2>
          <div class="space-y-5">
            ${recipe.ingredientGroups.map((group) => `
              <div class="space-y-2">
                <h3 class="text-xs font-bold uppercase tracking-wider text-[#f59e0b]">${group.groupName}</h3>
                <ul class="space-y-1.5 pl-4 list-disc marker:text-[#71717a] text-xs sm:text-sm text-[#d1d5db]">
                  ${group.items.map((item) => `<li class="leading-relaxed">${item}</li>`).join('')}
                </ul>
              </div>
            `).join('')}
          </div>
        </section>

        <section id="cara-pembuatan" class="mb-10 scroll-mt-24">
          <h2 class="text-xl font-bold text-[#ededef] tracking-tight pb-2 mb-5 border-b border-[#262830]">Cara Pembuatan</h2>
          <ol class="space-y-5 text-xs sm:text-sm text-[#d1d5db]">
            ${recipe.instructions.map((step) => `
              <li class="space-y-1">
                <div class="font-semibold text-[#ededef]">${step.stepNumber}. ${step.title}</div>
                <p class="text-xs sm:text-sm text-[#9ca3af] leading-relaxed pl-4">${step.description}</p>
              </li>
            `).join('')}
          </ol>
        </section>

        <section id="catatan" class="mb-10 scroll-mt-24">
          <h2 class="text-xl font-bold text-[#ededef] tracking-tight pb-2 mb-4 border-b border-[#262830]">Catatan (Wajib Dibaca)</h2>
          <div class="p-4 border border-[#262830] bg-[#16171b] rounded-none space-y-3">
            ${recipe.criticalNotes.map((note, i) => `
              <div class="space-y-1">
                <div class="text-xs sm:text-sm font-semibold text-[#fef3c7]">${i + 1}. ${note.title}</div>
                <p class="text-xs text-[#a1a1aa] leading-relaxed pl-3.5">${note.description}</p>
              </div>
            `).join('')}
          </div>
        </section>

        <section id="kebutuhan-dapur" class="mb-12 scroll-mt-24 pt-2 border-t border-[#262830]">
          <h2 class="text-lg font-bold text-[#ededef] tracking-tight mb-2">Kebutuhan Dapur</h2>
          <p class="text-xs text-[#71717a] mb-4">Rekomendasi bahan dan perlengkapan untuk resep ini:</p>
          <ul class="space-y-2 text-xs sm:text-sm">
            ${recipe.productLinks.map((prod) => `
              <li>
                <a href="${prod.externalUrl}" target="_blank" rel="noopener noreferrer" class="text-[#f59e0b] hover:underline">${prod.productName} ↗</a>
              </li>
            `).join('')}
          </ul>
        </section>
      </article>
    `;

    // Process HTML replacements
    let recipeHtml = baseHtml;

    // 1. Fix relative asset paths from 2 directory levels deep (../../assets/...)
    recipeHtml = recipeHtml.replace(/(href|src)="\.\/assets\//g, '$1="../../assets/');

    // 2. Replace Title & Meta Description
    recipeHtml = recipeHtml.replace(/<title>.*?<\/title>/, `<title>${fullTitle}</title>`);
    recipeHtml = recipeHtml.replace(/<meta name="description" content=".*?" \/>/, `<meta name="description" content="${fullSummary}" />`);

    // 3. Replace Canonical
    recipeHtml = recipeHtml.replace(/<link rel="canonical" href=".*?" \/>/, `<link rel="canonical" href="${recipeCanonical}" />`);

    // 4. Replace OpenGraph
    recipeHtml = recipeHtml.replace(/<meta property="og:title" content=".*?" \/>/, `<meta property="og:title" content="${fullTitle}" />`);
    recipeHtml = recipeHtml.replace(/<meta property="og:description" content=".*?" \/>/, `<meta property="og:description" content="${fullSummary}" />`);
    recipeHtml = recipeHtml.replace(/<meta property="og:url" content=".*?" \/>/, `<meta property="og:url" content="${recipeCanonical}" />`);
    recipeHtml = recipeHtml.replace(/<meta property="og:type" content=".*?" \/>/, `<meta property="og:type" content="article" />`);
    recipeHtml = recipeHtml.replace(/<meta property="og:image" content=".*?" \/>/, `<meta property="og:image" content="${ogImageUrl}" />`);

    // 5. Replace Twitter
    recipeHtml = recipeHtml.replace(/<meta name="twitter:title" content=".*?" \/>/, `<meta name="twitter:title" content="${fullTitle}" />`);
    recipeHtml = recipeHtml.replace(/<meta name="twitter:description" content=".*?" \/>/, `<meta name="twitter:description" content="${fullSummary}" />`);
    recipeHtml = recipeHtml.replace(/<meta name="twitter:image" content=".*?" \/>/, `<meta name="twitter:image" content="${ogImageUrl}" />`);

    // 6. Inject Recipe Schema JSON-LD into <head>
    const scriptTag = `\n    <script type="application/ld+json">${JSON.stringify(recipeJsonLd, null, 2)}</script>\n  </head>`;
    recipeHtml = recipeHtml.replace('</head>', scriptTag);

    // 7. Inject Pre-rendered Content into <div id="root">
    recipeHtml = recipeHtml.replace('<div id="root"></div>', `<div id="root">${preRenderedContent}</div>`);

    // Write file
    fs.writeFileSync(path.join(recipeDir, 'index.html'), recipeHtml, 'utf-8');
    console.log(`Generated pre-rendered SSG page: /resep/${recipe.slug}/index.html`);
  }

  // 2. Generate sitemap.xml
  const today = new Date().toISOString().split('T')[0];
  const sitemapUrls = [
    `  <url>\n    <loc>${siteUrl}/</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>1.0</priority>\n  </url>`,
    ...RAW_RECIPES.map((recipe) => (
      `  <url>\n    <loc>${siteUrl}/resep/${recipe.slug}/</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>0.8</priority>\n  </url>`
    )),
  ];

  const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemapUrls.join('\n')}\n</urlset>`;
  fs.writeFileSync(path.join(distDir, 'sitemap.xml'), sitemapXml, 'utf-8');
  console.log('Generated sitemap.xml');

  // 3. Generate robots.txt
  const robotsTxt = `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`;
  fs.writeFileSync(path.join(distDir, 'robots.txt'), robotsTxt, 'utf-8');
  console.log('Generated robots.txt');

  // 4. Generate 404.html for GitHub Pages fallback
  fs.writeFileSync(path.join(distDir, '404.html'), baseHtml, 'utf-8');
  console.log('Generated 404.html');

  // 5. Ensure og-image.jpg exists in dist root by copying from assets
  const firstJpg = assetFiles.find((f) => f.endsWith('.jpg'));
  if (firstJpg) {
    fs.copyFileSync(path.join(assetsDir, firstJpg), path.join(distDir, 'og-image.jpg'));
    console.log('Generated dist/og-image.jpg');
  }
}

generatePrerender();
